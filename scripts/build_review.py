def apply_review(rows, cols, review, key_col, check_col, result_col, memo_col, pri_col):
    """Return (review-sheet rows, final rows). Review rows keep collected values + review columns; final rows apply 'set'."""
    out_review, out_final = [], []
    for r in rows:
        r = list(r) + [""] * (len(cols) - len(r))
        rv = review.get(r[key_col])
        if rv:
            r[result_col], r[memo_col] = rv["result"], rv["memo"]
            if "check" in rv:
                r[check_col] = rv["check"]
                if not rv["check"]:
                    r[pri_col] = "해결"
        out_review.append(r)
        f = list(r)
        for col, val in (rv or {}).get("set", {}).items():
            f[cols.index(col)] = val
        out_final.append(f)
    return out_review, out_final


